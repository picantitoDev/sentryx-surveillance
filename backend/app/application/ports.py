
"""Contracts owned by the use cases; adapters implement them structurally."""
from typing import Protocol, Any
from app.domain.inference import Window, Prediction
from app.domain.camera import CameraRegistration

class Predictor(Protocol):
    def predict(self, window: Window) -> Prediction: ...

class CameraRepository(Protocol):
    def get(self, source_id: str) -> CameraRegistration | None: ...
    def list(self) -> list[CameraRegistration]: ...
    def save(self, camera: CameraRegistration, *, update: bool = False) -> bool: ...
    def delete(self, source_id: str) -> bool: ...

class SourceGateway(Protocol):
    def active(self, source_id: str) -> Any: ...
    def snapshot(self, session: Any) -> dict: ...
    def open(self, camera: CameraRegistration) -> dict: ...
    async def close(self, session_id: str) -> None: ...

class DetectionRepository(Protocol):
    def save(self, prediction: dict, camera: str, *, session_id=None, window_id=None) -> dict: ...
    def list(self, camera=None, limit=100, offset=0) -> list[dict]: ...
    def get(self, identifier: str) -> dict | None: ...

class AlertRepository(Protocol):
    def apply(self, result: dict, detection: dict) -> dict | None: ...
    def interrupt(self, session_id=None, reason='service_restarted') -> int: ...
    def list(self, camera=None, status=None, limit=100, offset=0) -> dict: ...
    def get(self, identifier: str) -> dict | None: ...

class LogRepository(Protocol):
    def emit(self, event_type: str, message: str, **details) -> dict | None: ...
    def list(self, **filters) -> dict: ...
    def get(self, identifier: str) -> dict | None: ...
